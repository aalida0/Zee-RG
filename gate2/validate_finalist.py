"""Uniform validation of a finalist (referee plan, 'Perform fine-grid, matching and full-Yukawa validation of finalists').

One record per point with, each reported separately and never merged into a single 'bound':
  tree      fine-grid (100 scales/decade) scale over the 13 prescribed variants (cert.FULL) with the tree-level boundary.  Computed with gate2/benchmarks.piece, i.e. with the SAME kernel,
            grid and cache as the benchmark records (benchmarks.py), so there is one verified tree-level record per (point, variant).  NOT cert.cert, whose default is five variants at ten
            scales per decade (a screening estimate for campaign chains)
  margins   V_red margin, lambda_h (pure singlet direction) and the conservative min(V_red, lambda_h), largest quartic, unitarity
  matching  for each prescription (ep, full-{sym,min,max}, full-hpole-{sym,min,max}): minimum scale over the re-matched variants, with the qscale stress variants separate,
            matched BFB margin, number of match failures, boundary (start) failures and numerical stops -- none of them is ever turned into a scale
  yukawa    all Yukawa couplings evolved with the tree boundary ('tree') and COMBINED with the matched boundary of each of the seven prescriptions (same completeness semantics);
            size of the beta-function component outside the real quartic subspace ('proj_resid' relative, 'proj_accum' integrated over ln mu): the CP-odd / imaginary parts generated by
            complex Yukawa couplings are NOT evolved, these numbers only say how large the neglected part is
  hw        exact range of the CLFV rates over the H+-W-+gamma multiplier |s| <= 1 (gate2/hw_envelope.py)
  vacuum    multistart global-minimum search of the TREE-LEVEL potential at the input point and tree boundary (not a proof, and not a check of the matched effective potential: the LFV
            and collider quantities are likewise computed from the input spectrum and mixing, not from the matched parameters)
  assessment  coverage (which of the expected prescriptions/modes were run), EP-clean (the effective-potential prescription alone) versus all-prescription robust, robust scale with its
            basis, and the proposed selection targets of the referee plan as information (not as physical thresholds)
  meta      source hash, git commit, inputs, grids; the record is reproducible from these
Usage: ZEE_INPUTS=modern ZEE_CACHE=<writable dir> python3 -W ignore gate2/validate_finalist.py NAME [--procs N] [--skip matching,yukawa,vacuum] [--modes ep,...] [--yukawa-modes tree,ep,...]
         -> $ZEE_OUT/validate_<NAME>.json   (NAME in benchmarks_input.json, S<i> of campaign_starts.json, or a path to a json with x and eta)
       python3 gate2/validate_finalist.py FILE.json --reassess      print the assessment recomputed from a stored record with the current logic (writes nothing)
A partial run (--modes ep, --skip ...) is recorded as partial: all_prescriptions_complete and robust_scale require every one of the seven matching prescriptions at all 13 variants."""
import sys, os, json, time, argparse, numpy as np
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path[:0] = [ROOT, os.path.join(ROOT, 'gate1'), os.path.join(ROOT, 'gate2')]
os.environ.setdefault('ZEE_INPUTS', 'modern')
MODES = ('ep', 'full-sym', 'full-min', 'full-max', 'full-hpole-sym', 'full-hpole-min', 'full-hpole-max')
HPOLE = ('full-hpole-sym', 'full-hpole-min', 'full-hpole-max')
N_VARIANTS = 13          # len(cert.FULL)
CLEAN_MIN = 10.0         # log10(Lambda/GeV) used for the 'EP-clean' label of the finalist screen (a screening convention, not a physical bound)


def _load(name):
    if os.path.exists(name): d = json.load(open(name))
    else:
        inp = json.load(open(os.path.join(ROOT, 'results', 'benchmarks_input.json')))
        st = {('S%d' % i): d for i, d in enumerate(json.load(open(os.path.join(ROOT, 'results', 'campaign_starts.json'))))}
        d = inp[name] if name in inp else st[name]
    return np.array(d['x'], float), np.array(d['eta'], float)


def task(a):
    kind, name, arg = a; t = time.time(); x, eta = _load(name)
    import bench, cert as CE, matched_scales as MS, yukawa_run as YR, hw_envelope as HE
    if kind == 'tree':
        import benchmarks as BMK                    # shared verified tree-level record: bench.trajectory at 100 scales per decade, cached per (point, variant, code hash)
        out = {}
        for p in CE.FULL:
            r_ = BMK.piece(x, eta, p); f_ = None if r_.get('fail') is None else str(r_['fail'])
            out[p] = dict(log10=float(r_['log10Lambda']), fail=f_, status=CE.variant_status(f_))
        el = [o['log10'] for o in out.values() if CE.eligible(o['status'])]
        res = dict(min=min(el) if el else None, complete=len(el) == len(out), n_variants=len(out), n_per_dec=100,
                   source='gate2/benchmarks.piece (bench.trajectory, 100 scales/decade)', variants=out)
    elif kind == 'match':
        v = {p: MS.piece_matched(x, eta, p, 1.0, mode=arg) for p in CE.FULL}; S = MS.summarize(v)
        S['bfb_margin_min'] = min((r['bfb_margin'] for r in v.values() if 'bfb_margin' in r), default=None); S['variants'] = v; res = S
    elif kind == 'yukawa':
        m, out = YR.cert_full(x, eta, 'all', match=None if arg == 'tree' else arg, n_per_dec=100)
        res = dict(min=m, match=None if arg == 'tree' else arg, n_per_dec=100, **YR.summarize_variants(out), variants=out)
    elif kind == 'hw':
        res = HE.envelope(x, eta)
    elif kind == 'vacuum':
        sc, c = bench.coup(x, eta); res = bench.deep_vacuum(c, sc, n=1500)
    elif kind == 'margins':
        sc, c = bench.coup(x, eta); vb, u, mx = bench.margins(c); lh = float(c[10]); res = dict(vred=float(vb), lambda_h=lh, conservative=float(min(vb, lh)), max_unit=float(u), max_quartic=float(mx), quartics=[float(v) for v in c])
    else: raise ValueError(kind)
    return kind, arg, res, time.time() - t


def assess(rec):
    """information for the selection targets of the referee plan; never a verdict on physics.
    Fail-closed on coverage: all_prescriptions_complete / robust_scale require EXACTLY the seven expected matching prescriptions, each with all 13 variants having a scale
    from a physical first failure or a ceiling (cert.variant_status); a partial run (for example --modes ep) is EP-clean at best.  EP-clean and all-prescription robust are distinct labels."""
    a = {}; mt = rec.get('matching', {}); sel = {k: v for k, v in mt.items() if v.get('n_variants')}
    miss = [m for m in MODES if m not in sel]; short = sorted(k for k, v in sel.items() if v['n_variants'] != N_VARIANTS)
    a['coverage'] = dict(matching_expected=list(MODES), matching_run=sorted(sel), matching_missing=miss, matching_wrong_variant_count=short, variants_expected=N_VARIANTS)
    cov = bool(sel) and not miss and not short
    if sel:
        a['all_prescriptions_complete'] = bool(cov and all(v['complete'] for v in sel.values()))
        a['n_prescriptions_complete'] = int(sum(bool(v['complete']) and v['n_variants'] == N_VARIANTS for v in sel.values())); a['n_prescriptions_expected'] = len(MODES)
        a['n_start_failures_total'] = int(sum(v['n_start_fail'] for v in sel.values())); a['n_match_failures_total'] = int(sum(v['n_match_failed'] for v in sel.values()))
        a['n_numerical_stops_total'] = int(sum(v.get('n_numerical', 0) for v in sel.values()))
        defined = [v['min_stress'] for v in sel.values() if v['min_stress'] is not None]
        a['min_scale_over_prescriptions_defined_only'] = min(defined) if defined else None
        mm = [v['bfb_margin_min'] for v in sel.values() if v.get('bfb_margin_min') is not None]; a['min_matched_bfb_margin'] = min(mm) if mm else None
        ep = sel.get('ep')
        a['ep_clean'] = bool(ep and ep['n_variants'] == N_VARIANTS and ep['complete'] and ep['n_start_fail'] == 0 and ep.get('min_stress') is not None and ep['min_stress'] >= CLEAN_MIN)
        rob_match = a['min_scale_over_prescriptions_defined_only'] if a['all_prescriptions_complete'] else None
    else:
        a['all_prescriptions_complete'] = False; a['ep_clean'] = False; rob_match = None
    a['robust_scale_matching_only'] = rob_match
    y = rec.get('yukawa', {}); comb = {m: y[m] for m in MODES if m in y}
    a['coverage']['yukawa_combined_missing'] = [m for m in MODES if m not in y]
    comb_ok = len(comb) == len(MODES) and all(v.get('complete') is True and v.get('n_variants') == N_VARIANTS and v.get('min') is not None for v in comb.values())
    a['all_combined_yukawa_complete'] = bool(comb_ok)
    a['robust_scale_combined_yukawa'] = min(v['min'] for v in comb.values()) if comb_ok else None
    if rob_match is not None and comb_ok: a['robust_scale'] = min(rob_match, a['robust_scale_combined_yukawa']); a['robust_scale_basis'] = 'minimum over 7 matching prescriptions x 13 variants and over 7 combined matching+all-Yukawa runs x 13 variants'
    elif rob_match is not None: a['robust_scale'] = rob_match; a['robust_scale_basis'] = 'minimum over 7 matching prescriptions x 13 variants (production top-only RGEs); the combined all-Yukawa runs are not complete'
    else: a['robust_scale'] = None; a['robust_scale_basis'] = 'none: coverage incomplete or some variant has no scale from a physical first failure'
    if a['robust_scale'] is not None and a['robust_scale'] >= CLEAN_MIN: a['classification'] = 'robust over all seven prescriptions'
    elif a['ep_clean']: a['classification'] = 'EP-clean only (not all prescriptions complete or run)'
    else: a['classification'] = 'not clean'
    t = rec.get('tree')
    if t: a['tree_complete'] = bool(t.get('complete')) and t.get('n_variants') == N_VARIANTS; a['tree_min'] = t.get('min')
    mg = rec.get('margins')
    if mg: a['conservative_tree_margin'] = mg['conservative']; a['max_quartic'] = mg['max_quartic']
    if y:
        a['yukawa_min_scale'] = {k: v['min'] for k, v in y.items()}
        pr = [o['proj_resid'] for v in y.values() for o in v.get('variants', {}).values() if o.get('proj_resid') is not None]; ac = [o['proj_accum'] for v in y.values() for o in v.get('variants', {}).values() if o.get('proj_accum') is not None]
        a['quartic_component_outside_real_subspace'] = dict(max_relative=max(pr) if pr else None, max_integrated=max(ac) if ac else None)
    tg = {}
    if a.get('robust_scale') is not None: tg['robust_scale_above_1e10'] = a['robust_scale'] > 10.0
    if a.get('conservative_tree_margin') is not None: tg['margin_above_0.05'] = a['conservative_tree_margin'] > 0.05
    if a.get('max_quartic') is not None: tg['quartics_below_1'] = a['max_quartic'] < 1.0
    a['plan_targets'] = tg
    return a


def provenance(x, eta):
    import hashlib, glob, subprocess, cert as CE
    src = sorted(glob.glob(os.path.join(ROOT, 'zee', '*.py')) + glob.glob(os.path.join(ROOT, 'gate2', '*.py')))
    try: commit = subprocess.run(['git', '-C', ROOT, 'rev-parse', 'HEAD'], capture_output=True, text=True, timeout=20).stdout.strip() or None
    except Exception: commit = None
    return dict(code_hash=hashlib.sha256(b''.join(open(f, 'rb').read() for f in src)).hexdigest()[:16], git_commit=commit, zee_inputs=os.environ.get('ZEE_INPUTS'),
                variants=list(CE.FULL), matching_modes=list(MODES), tree_n_per_dec=100, yukawa_n_per_dec=100, vacuum_starts_requested=1500, x=[float(v) for v in x], eta=[float(v) for v in eta],
                scope='LFV, collider and vacuum quantities refer to the input spectrum and tree boundary; matching and RG runs are one-loop scalar-consistency estimates')


if __name__ == '__main__':
    ap = argparse.ArgumentParser(); ap.add_argument('name'); ap.add_argument('--procs', type=int, default=2); ap.add_argument('--skip', default='')
    ap.add_argument('--modes', default=','.join(MODES)); ap.add_argument('--yukawa-modes', default='tree,' + ','.join(MODES)); ap.add_argument('--reassess', action='store_true')
    ar = ap.parse_args(); skip = set(filter(None, ar.skip.split(',')))
    if ar.reassess:
        print(json.dumps(assess(json.load(open(ar.name))), indent=1, default=float)); sys.exit(0)
    jobs = []
    if 'matching' not in skip: jobs += [('match', ar.name, m) for m in ar.modes.split(',')]
    if 'yukawa' not in skip: jobs += [('yukawa', ar.name, m) for m in ar.yukawa_modes.split(',')]
    for k in ('tree', 'hw', 'margins') + (() if 'vacuum' in skip else ('vacuum',)): jobs.append((k, ar.name, None))
    from multiprocessing import Pool
    x_, eta_ = _load(ar.name)
    rec = dict(name=ar.name, meta=provenance(x_, eta_), matching={}, yukawa={}, timing={})
    with Pool(ar.procs) as P:
        for kind, arg, res, dt in P.imap_unordered(task, jobs):
            if kind == 'match': rec['matching'][arg] = res
            elif kind == 'yukawa': rec['yukawa'][arg] = res
            else: rec[kind] = res
            rec['timing']['%s:%s' % (kind, arg)] = dt; print('done', kind, arg, '%.0fs' % dt, flush=True)
    rec['assessment'] = assess(rec)
    outdir = os.environ.get('ZEE_OUT', os.path.join(ROOT, 'results', 'validation'))
    try: os.makedirs(outdir, exist_ok=True)
    except OSError: outdir = '/tmp'
    json.dump(rec, open(os.path.join(outdir, 'validate_%s.json' % os.path.basename(ar.name).replace('.json', '')), 'w'), indent=1, default=float)
    print(json.dumps(rec['assessment'], indent=1, default=float))
